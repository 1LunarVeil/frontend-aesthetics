class ScanTests(unittest.TestCase):
    def test_tells_fixture_triggers_expected_rules(self):
        findings, scanned = slop_scan.scan([str(FIXTURES / "tells" / "index.html")])
        rules = {finding.rule for finding in findings}
        expected = {
            "A11Y-ZOOM", "A11Y-IMG-ALT", "A11Y-FOCUS-REMOVED", "A11Y-TABINDEX",
            "A11Y-REDUCED-MOTION", "TYPE-TINY", "TYPE-DEFAULT-PRIMARY", "TYPE-CAPS",
            "MOTION-ALL", "MOTION-GENERIC-ENTRANCE", "COLOR-PURPLE-GRADIENT",
            "COLOR-PURE-BLACK", "COLOR-GREY-SHADOW", "COLOR-RAW-HEX", "COPY-LOREM",
            "COPY-GENERIC-ERROR", "COPY-SUBMIT", "COPY-ARROW-CTA", "COPY-MIDDOT-META",
        }
        self.assertEqual(expected - rules, set())
        self.assertEqual(scanned, 1)

    def test_clean_fixture_has_no_blocking_or_important_findings(self):
        findings, _ = slop_scan.scan([str(FIXTURES / "clean" / "app.css")])
        self.assertEqual([f for f in findings if f.severity in ("blocking", "important")], [])

    def test_comment_lines_are_not_scanned(self):
        text = '/* transition: all 0.3s; */\n// <img src="a.png">\n'
        self.assertEqual(slop_scan.scan_text(Path("x.html"), text), [])

    def test_layout_transition_is_review_level(self):
        findings = slop_scan.scan_text(Path("x.css"), ".drawer { transition: width 0.2s; }\n")
        self.assertEqual([(f.rule, f.severity) for f in findings], [("MOTION-LAYOUT", "review")])

    def test_exit_status_reflects_blocking_findings(self):
        code, _ = run(slop_scan.main, [str(FIXTURES / "tells" / "index.html")])
        self.assertEqual(code, 1)
        code, _ = run(slop_scan.main, [str(FIXTURES / "clean" / "app.css")])
        self.assertEqual(code, 0)

    def test_fixture_directories_are_skipped_when_scanning_a_folder(self):
        _, scanned = slop_scan.scan([str(TESTS)])
        self.assertEqual(scanned, 0)


class ImageDiffTests(unittest.TestCase):
    """Fixtures are generated by tests/make_fixtures.py, so no binary blobs ship."""

    @classmethod
    def setUpClass(cls):
        png = FIXTURES / "png"
        if not (png / "flat.png").exists() or not (png / "box.png").exists():
            import make_fixtures
            make_fixtures.main()
        cls.flat = png / "flat.png"
        cls.box = png / "box.png"

    def test_decodes_known_dimensions(self):
        width, height, pixels = image_diff.decode_png(self.flat)
        self.assertEqual((width, height), (64, 40))
        self.assertEqual(len(pixels), 64 * 40 * 3)
        self.assertEqual(tuple(pixels[:3]), (246, 247, 249))

    def test_diff_locates_the_rectangle_exactly(self):
        result = image_diff.diff(self.flat, self.box)
        self.assertTrue(result["comparable"])
        self.assertEqual(result["changed_pixels"], 30 * 16)
        self.assertEqual(result["bounding_box"], {"x": 10, "y": 8, "width": 30, "height": 16})

    def test_identical_images_report_identical(self):
        result = image_diff.diff(self.flat, self.flat)
        self.assertTrue(result["identical"])
        self.assertEqual(result["changed_pixels"], 0)

    def test_size_mismatch_is_not_compared_silently(self):
        import struct
        import zlib

        # A 32x20 flat PNG: same colour, different size.
        raw = bytearray()
        for _ in range(20):
            raw += b"\x00" + bytes((246, 247, 249)) * 32
        header = struct.pack(">IIBBBBB", 32, 20, 8, 2, 0, 0, 0)
        chunks = (
            b"\x89PNG\r\n\x1a\n"
            + struct.pack(">I", len(header)) + b"IHDR" + header
            + struct.pack(">I", zlib.crc32(b"IHDR" + header) & 0xFFFFFFFF)
            + struct.pack(">I", len(zlib.compress(bytes(raw), 9))) + b"IDAT" + zlib.compress(bytes(raw), 9)
            + struct.pack(">I", zlib.crc32(b"IDAT" + zlib.compress(bytes(raw), 9)) & 0xFFFFFFFF)
            + struct.pack(">I", 0) + b"IEND" + struct.pack(">I", zlib.crc32(b"IEND") & 0xFFFFFFFF)
        )
        smaller = FIXTURES / "png" / "small.png"
        smaller.write_bytes(chunks)
        try:
            result = image_diff.diff(self.flat, smaller)
            self.assertFalse(result["comparable"])
            self.assertIn("size mismatch", result["reason"])
        finally:
            smaller.unlink(missing_ok=True)

    def test_stats_distinguishes_flat_from_structured(self):
        flat = image_diff.stats(self.flat)
        box = image_diff.stats(self.box)
        self.assertEqual(flat["distinct_colors_sampled"], 1)
        self.assertGreater(box["distinct_colors_sampled"], flat["distinct_colors_sampled"])

    def test_non_png_input_is_reported_not_crashed(self):
        code, out = run(image_diff.main, [str(TESTS / "test_design_tools.py")])
        self.assertEqual(code, 2)
        self.assertIn("not a PNG", out)

    def test_decompression_bomb_is_rejected_before_inflating(self):
        """A tiny file must not be able to inflate past the declared size.

        Reproduced before the fix: a 65 KB PNG declared 1x1 inflated to 64 MB
        and was accepted, because the length check ran after decompression.
        """
        import struct
        import time
        import zlib

        payload = b"\x00" * (32 * 1024 * 1024)
        compressed = zlib.compress(payload, 9)
        header = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)

        def chunk(kind, body):
            return (struct.pack(">I", len(body)) + kind + body
                    + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF))

        bomb = FIXTURES / "png" / "bomb.png"
        bomb.write_bytes(
            b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", compressed) + chunk(b"IEND", b"")
        )
        try:
            started = time.time()
            with self.assertRaises(image_diff.Unsupported) as caught:
                image_diff.decode_png(bomb)
            elapsed = time.time() - started
            self.assertIn("decompression bomb", str(caught.exception))
            self.assertLess(elapsed, 2.0, "rejection must not decompress the payload first")
        finally:
            bomb.unlink(missing_ok=True)

    def test_declared_dimensions_above_the_pixel_limit_are_rejected(self):
        import struct
        import zlib
        header = struct.pack(">IIBBBBB", 200_000, 200_000, 8, 2, 0, 0, 0)

        def chunk(kind, body):
            return (struct.pack(">I", len(body)) + kind + body
                    + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF))

        huge = FIXTURES / "png" / "huge.png"
        huge.write_bytes(
            b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(b"\x00" * 16)) + chunk(b"IEND", b"")
        )
        try:
            with self.assertRaises(image_diff.Unsupported) as caught:
                image_diff.decode_png(huge)
            self.assertIn("pixel limit", str(caught.exception))
        finally:
            huge.unlink(missing_ok=True)


class VisualCaptureUrlTests(unittest.TestCase):
    def test_option_like_url_is_rejected(self):
        with self.assertRaises(visual_capture.UrlRejected):
            visual_capture.validate_url("--screenshot=/etc/passwd")

    def test_non_http_schemes_are_rejected(self):
        for url in ("file:///C:/Windows/win.ini", "javascript:alert(1)", "ftp://example.com"):
            with self.assertRaises(visual_capture.UrlRejected, msg=url):
                visual_capture.validate_url(url)

    def test_loopback_is_allowed(self):
        self.assertEqual(visual_capture.validate_url("http://127.0.0.1:8080/"), "http://127.0.0.1:8080/")

    def test_link_local_and_private_need_an_explicit_flag(self):
        for url in ("http://169.254.169.254/latest/meta-data", "http://10.0.0.5/"):
            with self.assertRaises(visual_capture.UrlRejected, msg=url):
                visual_capture.validate_url(url)
            self.assertEqual(
                visual_capture.validate_url(url, allow_private=True), url
            )


if __name__ == "__main__":
    unittest.main()
